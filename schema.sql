CREATE SCHEMA IF NOT EXISTS market;

CREATE TABLE IF NOT EXISTS market.daily_prices (
    symbol            text    NOT NULL,
    trade_date_jalali text    NOT NULL,
    time              text,
    tno               bigint,
    tvol              bigint,
    tval              numeric,
    pmin              numeric,
    pmax              numeric,
    py                numeric,
    pf                numeric,
    pl                numeric,
    plc               numeric,
    plp               numeric,
    pc                numeric,
    pcc               numeric,
    pcp               numeric,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (symbol, trade_date_jalali)
);

CREATE TABLE IF NOT EXISTS market.option_contracts (
    isin text PRIMARY KEY,
    contract_id bigint,
    option_symbol text,
    contract_name text,
    underlying_symbol text,
    underlying_id bigint,
    underlying_last_price numeric,
    underlying_closing_price numeric,
    underlying_previous_price numeric,
    underlying_price_change_percent numeric,
    option_type text,
    start_date text,
    expiration_date text,
    days_remaining bigint,
    contract_size bigint,
    strike_price numeric,
    open_interest bigint,
    last_price numeric,
    closing_price numeric,
    previous_price numeric,
    first_price numeric,
    min_price numeric,
    max_price numeric,
    trade_count bigint,
    trade_volume bigint,
    trade_value numeric,
    notional_value numeric,
    industry text,
    industry_id bigint,
    lower_price_limit numeric,
    upper_price_limit numeric,
    snapshot_time text,
    last_updated_at timestamptz NOT NULL DEFAULT now()
);
